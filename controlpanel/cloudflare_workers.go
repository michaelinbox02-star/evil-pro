// cfAllowTurnstileHost makes sure a Turnstile widget's allowed domains include
// host. Turnstile validates the page hostname, so a brand new workers.dev host is
// rejected ("Unable to connect to website") and the gate never clears until the
// host is listed: the widget renders, __tsOnPass never fires, and the visitor is
// parked on the branded page.
//
// PUT is used, not PATCH: with a token, PATCH answers 10405 "Method not allowed
// for this authentication scheme". Returns true when a change was made.
func cfAllowTurnstileHost(token, accountID, siteKey, host string) (bool, error) {
	if siteKey == "" || host == "" {
		return false, nil
	}
	raw, err := cfDo(token, "GET", "/accounts/"+accountID+"/challenges/widgets/"+url.PathEscape(siteKey), nil)
	if err != nil {
		return false, cfPermHint(err, "Turnstile:Read")
	}
	var w struct {
		Name    string   `json:"name"`
		Mode    string   `json:"mode"`
		Domains []string `json:"domains"`
	}
	if err := json.Unmarshal(raw, &w); err != nil {
		return false, err
	}
	for _, d := range w.Domains {
		if strings.EqualFold(strings.TrimSpace(d), host) {
			return false, nil
		}
	}
	domains := append(append([]string{}, w.Domains...), host)
	body := map[string]interface{}{"name": w.Name, "mode": w.Mode, "domains": domains}
	if _, err := cfDo(token, "PUT", "/accounts/"+accountID+"/challenges/widgets/"+url.PathEscape(siteKey), body); err != nil {
		return false, cfPermHint(err, "Turnstile:Edit")
	}
	return true, nil
}
