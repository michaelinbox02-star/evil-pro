type cfAccount struct {
	ID   string `json:"id"`
	Name string `json:"name"`
}

// cfAccountIDFromZone resolves the account that owns the zone for domain. The
// account id is read off the zone object, which works for zone-scoped tokens
// (GET /accounts needs account scope and often returns nothing for those).
func cfAccountIDFromZone(token, domain string) (string, error) {
	zoneID, err := cfZoneID(token, domain)
	if err != nil {
		return "", cfPermHint(err, "Zone:Read")
	}
	raw, err := cfDo(token, "GET", "/zones/"+zoneID, nil)
	if err != nil {
		return "", cfPermHint(err, "Zone:Read")
	}
	var z struct {
		Account cfAccount `json:"account"`
	}
	if err := json.Unmarshal(raw, &z); err != nil {
		return "", err
	}
	if z.Account.ID == "" {
		return "", fmt.Errorf("cloudflare: zone lookup returned no account id")
	}
	return z.Account.ID, nil
}

// cfWorkersSubdomain reads the account's workers.dev subdomain. Empty string
// means the account has none yet (Cloudflare error 10007); the dashboard normally
// creates it on first visit, but the API does not.
func cfWorkersSubdomain(token, accountID string) (string, error) {
	raw, err := cfDo(token, "GET", "/accounts/"+accountID+"/workers/subdomain", nil)
	if err != nil {
		var ae *cfAPIError
		if errors.As(err, &ae) && ae.Code == 10007 {
			return "", nil
		}
		return "", cfPermHint(err, "Workers Scripts:Read")
	}
	var res struct {
		Subdomain string `json:"subdomain"`
	}
	if err := json.Unmarshal(raw, &res); err != nil {
		return "", err
	}
	return res.Subdomain, nil
}

// cfEnsureWorkersSubdomain returns the account's workers.dev subdomain, creating
// it from suggestion when the account has none.
func cfEnsureWorkersSubdomain(token, accountID, suggestion string) (string, error) {
	sub, err := cfWorkersSubdomain(token, accountID)
	if err != nil || sub != "" {
		return sub, err
	}
	name := strings.ToLower(strings.TrimSpace(suggestion))
	re := regexp.MustCompile(`[^a-z0-9-]+`)
	name = re.ReplaceAllString(name, "-")
	name = strings.Trim(name, "-")
	if name == "" {
		name = "evilpro"
	}
	if len(name) < 3 {
		name = "evilpro"
	}
	raw, err := cfDo(token, "PUT", "/accounts/"+accountID+"/workers/subdomain",
		map[string]string{"subdomain": name})
	if err != nil {
		return "", cfPermHint(err, "Workers Scripts:Edit")
	}
	var res struct {
		Subdomain string `json:"subdomain"`
	}
	if err := json.Unmarshal(raw, &res); err != nil {
		return "", err
	}
	return res.Subdomain, nil
}

// cfPutWorkerScript uploads (or updates) a classic Worker script.
func cfPutWorkerScript(token, accountID, name, source string) error {
	req, err := http.NewRequest("PUT",
		cfAPI+"/accounts/"+accountID+"/workers/scripts/"+url.PathEscape(name),
		strings.NewReader(source))
	if err != nil {
		return err
	}
	req.Header.Set("Authorization", "Bearer "+token)
	req.Header.Set("Content-Type", "application/javascript")
	resp, err := cfHTTP.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	raw, _ := io.ReadAll(resp.Body)
	var env cfEnvelope
	if err := json.Unmarshal(raw, &env); err != nil {
		return &cfAPIError{Status: resp.StatusCode}
	}
	if !env.Success {
		e := &cfAPIError{Status: resp.StatusCode}
		for _, x := range env.Errors {
			e.Code, e.Message = x.Code, x.Message
			break
		}
		return cfPermHint(e, "Workers Scripts:Edit")
	}
	return nil
}

// cfEnableWorkerRoute turns the script's workers.dev route on or off.
